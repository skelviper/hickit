static int validate_file_prefix(const char *label, const char *path, const char *header_token)
{
	char *prefix;
	int failed = 0;

	failed |= check_true(label, file_exists(path));
	failed |= check_true("matrix output size positive", file_size_or_negative(path) > 0);
	prefix = read_file_prefix(path, HK_BLIND_P9016_MATRIX_PREFIX_SCAN);
	failed |= check_true("matrix output prefix readable", prefix != 0);
	if (prefix == 0) return 1;
	failed |= check_true("matrix output header token", strstr(prefix, header_token) != 0);
	free(prefix);
	return failed;
}

