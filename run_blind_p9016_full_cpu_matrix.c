static int compute_homolog_sep_force_l1(const struct hk_bmap *bmap, const fvec3_t *coords,
										float unit, float min_sep_unit, float lambda_sep,
										float *force_l1, int32_t *n_nonfinite)
{
	fvec3_t *force = 0;
	int32_t n_diploid;
	double l1 = 0.0;
	int32_t i;
	int a;

	assert(bmap);
	assert(force_l1);
	assert(n_nonfinite);
	*force_l1 = 0.0f;
	*n_nonfinite = 0;
	n_diploid = bmap->n_beads * HK_DIPLOID_N_COPY;
	if (n_diploid <= 0) return 0;
	assert(coords);
	force = (fvec3_t*)calloc((size_t)n_diploid, sizeof(*force));
	if (force == 0) return -1;
	(void)hk_blind_homolog_sep_accumulate_force(bmap->n_beads, coords, force,
												 unit, min_sep_unit, lambda_sep);
	for (i = 0; i < n_diploid; ++i) {
		for (a = 0; a < 3; ++a) {
			if (isfinite(force[i][a]))
				l1 += fabs((double)force[i][a]);
			else
				++*n_nonfinite;
		}
	}
	free(force);
	*force_l1 = (float)l1;
	return 0;
}

