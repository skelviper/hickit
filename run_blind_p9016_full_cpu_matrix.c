static int validate_summary_file(const char *summary_path, int n_expected)
{
	FILE *fp = fopen(summary_path, "r");
	char line[4096];
	int n_rows = -1;
	int failed = 0;
	if (fp == 0) return 1;
	while (fgets(line, sizeof(line), fp)) {
		if (n_rows < 0) {
			failed |= check_true("matrix summary header config", strstr(line, "config_name") != 0);
			failed |= check_true("matrix summary header init", strstr(line, "init_mode") != 0);
			failed |= check_true("matrix summary header audit", strstr(line, "audit_status") != 0);
		} else {
			failed |= check_true("matrix summary row status", strstr(line, "\tOK\t") != 0);
		}
		++n_rows;
	}
	if (ferror(fp)) failed = 1;
	fclose(fp);
	failed |= check_i32("matrix summary row count", n_rows, n_expected);
	return failed;
}

static int run_one_config(const struct matrix_config *config, struct hk_bmap *bmap,
						  const struct hk_blind_pair *raw, int32_t n_raw,
						  const char *root_dir,
						  const struct hk_blind_coarse_to_fine_map *coarse_to_fine,
						  const struct hk_bmap *fine_bmap,
						  int bin_size_bp, int write_raw, FILE *summary_fp,
						  struct matrix_result *result)
{
	struct hk_blind_bpair_set *set = 0;
	struct hk_fdg_conf fdg_conf;
	struct hk_blind_iter_schedule_conf schedule_conf;
	struct hk_blind_iter_loop_diag loop_diag;
	struct hk_blind_prior_diag prior_diag;
	struct hk_blind_base_k_stats base_k_stats;
	struct hk_blind_single_iter_diag *per_iter = 0;
	fvec3_t *haploid = 0;
	fvec3_t *diploid = 0;
	fvec3_t *init_diploid = 0;
	char posterior_path[1024], coords_path[1024], coords_gz_path[1024], diag_path[1024];
	char force_diag_path[1024], force_bpair_diag_path[1024], raw_path[1024], manifest_path[1024];
	int32_t n_diploid = bmap->n_beads * HK_DIPLOID_N_COPY;
	int failed = 0;

	memset(result, 0, sizeof(*result));
	result->config = config;
	path_join(result->output_dir, sizeof(result->output_dir), root_dir, config->name);
	if (mkdir(result->output_dir, 0700) != 0) {
		fprintf(stderr, "failed to create matrix config directory %s\n", result->output_dir);
		return 1;
	}
	path_join(posterior_path, sizeof(posterior_path), result->output_dir, "p9016_full.bpair_posterior.tsv");
	path_join(coords_path, sizeof(coords_path), result->output_dir, "p9016_full.coords.tsv");
	path_join(coords_gz_path, sizeof(coords_gz_path), result->output_dir, "p9016_full.coords.tsv.gz");
	path_join(diag_path, sizeof(diag_path), result->output_dir, "p9016_full.loop_diag.tsv");
	path_join(force_diag_path, sizeof(force_diag_path), result->output_dir, "p9016_full.force_class_diag.tsv");
	path_join(force_bpair_diag_path, sizeof(force_bpair_diag_path), result->output_dir, "p9016_full.force_bpair_diag.tsv");
	path_join(raw_path, sizeof(raw_path), result->output_dir, "p9016_full.raw_posterior.tsv");
	path_join(manifest_path, sizeof(manifest_path), result->output_dir, "p9016_full.manifest.tsv");

	fprintf(stderr, "P9016 matrix config %s: building binned set\n", config->name);
	set = hk_blind_bpair_set_build(bmap, n_raw, raw);
	failed |= check_binned_set(bmap, set, n_raw);
	failed |= check_i32("matrix base_k mode",
						hk_blind_bpair_set_apply_base_k_mode(bmap, set,
															 HK_BLIND_P9016_MATRIX_BASE_K_MODE), 0);
	if (config->d_scale_mode == HK_BLIND_D_SCALE_DENSITY_NORMALIZED_RAW_COUNT ||
		config->d_scale_mode == HK_BLIND_D_SCALE_CAPPED_DENSITY_RAW_COUNT) {
		if (coarse_to_fine == 0) {
			fprintf(stderr, "density-normalized d_scale requires coarse-to-fine exposure map\n");
			failed = 1;
		} else {
			failed |= check_i32("matrix density exposure map",
								hk_blind_bpair_set_apply_density_d_scale_from_map(
									set, coarse_to_fine, config->d_scale_mode,
									HK_BLIND_P9016_MATRIX_D_SCALE_EPS_COUNT), 0);
		}
	}
	failed |= check_i32("matrix prior init", init_prior_for_config(bmap, set, config, &prior_diag), 0);
	hk_blind_bpair_set_base_k_stats(set, &base_k_stats);
	if (failed) goto cleanup;

	haploid = (fvec3_t*)calloc((size_t)bmap->n_beads, sizeof(*haploid));
	diploid = (fvec3_t*)calloc((size_t)n_diploid, sizeof(*diploid));
	init_diploid = (fvec3_t*)calloc((size_t)n_diploid, sizeof(*init_diploid));
	per_iter = (struct hk_blind_single_iter_diag*)calloc((size_t)config->n_iter, sizeof(*per_iter));
	if (haploid == 0 || diploid == 0 || init_diploid == 0 || per_iter == 0) {
		fprintf(stderr, "failed to allocate matrix coordinate/diagnostic data for %s\n", config->name);
		failed = 1;
		goto cleanup;
	}
	failed |= check_i32("matrix init coords", init_coords_for_config(bmap, config, haploid, diploid), 0);
	failed |= check_coords_finite(diploid, n_diploid);
	if (failed) goto cleanup;
	memcpy(init_diploid, diploid, (size_t)n_diploid * sizeof(*init_diploid));

	fprintf(stderr, "P9016 matrix config %s: n_iter=%d relax_steps=%d\n",
			config->name, config->n_iter, config->relax_steps);
	hk_fdg_conf_init(&fdg_conf);
	fdg_conf.backend = HK_FDG_BACKEND_CPU;
	fdg_conf.k_rel_rep *= config->repulsion_multiplier;
	set_schedule_conf(&schedule_conf, config);
	failed |= check_i32("matrix scheduled ret",
						hk_blind_run_iter_loop_scheduled_cpu(bmap, set, &fdg_conf, diploid, 0,
															 &schedule_conf, per_iter, &loop_diag), 0);
	failed |= check_loop_health(config, &loop_diag, per_iter);
	failed |= check_coords_finite(diploid, n_diploid);
	failed |= validate_final_bpair_set(set);
	if (failed) goto cleanup;

	fprintf(stderr, "P9016 matrix config %s: writing outputs to %s\n",
			config->name, result->output_dir);
	failed |= check_i32("matrix write required outputs",
						write_required_outputs(posterior_path, coords_path, coords_gz_path, diag_path,
											   bmap, set, diploid, &loop_diag), 0);
	failed |= check_i32("matrix write force class diag",
						write_force_class_diag(force_diag_path, &fdg_conf, config, bmap, set, diploid,
											   config->n_iter > 0? &per_iter[config->n_iter - 1].relax_diag : 0), 0);
	failed |= check_i32("matrix write force bpair diag",
						write_force_bpair_diag(force_bpair_diag_path, &fdg_conf, config, bmap, set, diploid), 0);
	if (write_raw) {
		fprintf(stderr, "P9016 matrix config %s: HK_BLIND_WRITE_RAW=1, writing raw posterior\n",
				config->name);
		failed |= check_i32("matrix write raw output",
							write_optional_raw_output(raw_path, raw, n_raw, bmap, set), 0);
	}
	if (bin_size_bp != HK_BLIND_P9016_MATRIX_RESOLUTION && coarse_to_fine && fine_bmap) {
		fprintf(stderr, "P9016 matrix config %s: writing lifted 1Mb initialization\n",
				config->name);
		failed |= check_i32("matrix write lifted 1Mb output",
							write_lifted_1mb_outputs(result->output_dir, bmap, fine_bmap,
													  coarse_to_fine, diploid), 0);
		if (matrix_env_flag_enabled("HK_BLIND_P9016_MR_REFINE_1MB")) {
			failed |= check_i32("matrix lifted 1Mb anchored refinement",
								run_lifted_1mb_refinement(result->output_dir, config, bmap, fine_bmap,
														  coarse_to_fine, diploid, raw, n_raw), 0);
		}
	}
#if defined(HK_BLIND_P9016_SCAFFOLD_STAGE_DIAGNOSTICS)
	failed |= check_i32("matrix write scaffold stage outputs",
						write_scaffold_stage_outputs(result->output_dir, config, bmap, raw, n_raw,
													 haploid, init_diploid, diploid), 0);
#endif
	failed |= check_i32("matrix write manifest",
						write_manifest(manifest_path, result->output_dir, posterior_path, coords_path,
									   coords_gz_path, diag_path, force_diag_path, force_bpair_diag_path,
									   raw_path, write_raw, config,
									   bin_size_bp, coarse_to_fine != 0, bmap, set,
									   &prior_diag, &base_k_stats, &loop_diag), 0);
	if (failed) goto cleanup;

	failed |= validate_file_prefix("matrix bpair posterior", posterior_path, "p00");
	failed |= validate_file_prefix("matrix coords", coords_path, "diploid_bid");
	failed |= validate_file_prefix("matrix coords gz", coords_gz_path, "\037\213");
	failed |= validate_file_prefix("matrix loop diag", diag_path, "final_mean_entropy");
	failed |= validate_force_class_diag_prefix(force_diag_path);
	failed |= validate_force_bpair_diag_prefix(force_bpair_diag_path);
	failed |= validate_manifest_prefix(manifest_path, write_raw, config);
	if (write_raw)
		failed |= validate_file_prefix("matrix raw posterior", raw_path, "raw_id");
	if (failed) goto cleanup;

	if (bin_size_bp == HK_BLIND_P9016_MATRIX_RESOLUTION) {
		failed |= run_auditor(result->output_dir);
		if (failed) goto cleanup;
	} else {
		fprintf(stderr, "P9016 matrix config %s: skipping 1Mb-only output auditor for %s run\n",
				config->name, bin_size_bp == 4000000? "4Mb" : "non-1Mb");
	}

	result->n_raw = set->n_raw;
	result->n_bpair = set->n_bpairs;
	result->n_beads = bmap->n_beads;
	result->final_mean_entropy = loop_diag.final_mean_entropy;
	result->final_mean_pU = loop_diag.final_mean_pU;
	result->final_mean_sep = loop_diag.final_mean_sep;
	result->final_min_sep = loop_diag.final_min_sep;
	result->final_max_sep = loop_diag.final_max_sep;
	result->final_sum_wedge_k = loop_diag.final_sum_wedge_k;
	result->final_mean_rho_train_bpair = loop_diag.final_mean_rho_train_bpair;
	result->final_min_rho_train_bpair = loop_diag.final_min_rho_train_bpair;
	result->final_max_rho_train_bpair = loop_diag.final_max_rho_train_bpair;
	result->final_n_skipped_same_bin_bpairs = loop_diag.final_n_skipped_same_bin_bpairs;
	result->k_rel_rep_effective = fdg_conf.k_rel_rep;
	if (config->n_iter > 0) {
		result->final_contact_energy = per_iter[config->n_iter - 1].relax_diag.final_contact_energy;
		result->final_repulsion_energy = per_iter[config->n_iter - 1].relax_diag.final_repulsion_energy;
		result->final_backbone_energy = per_iter[config->n_iter - 1].relax_diag.final_backbone_energy;
	}
	result->posterior_refreshed_after_final_relax = loop_diag.posterior_refreshed_after_final_relax;
	result->n_same_bin_excluded = set->n_raw_same_bin_excluded;
	result->n_raw_cis = set->n_raw_cis;
	result->n_raw_trans = set->n_raw_trans;
	result->n_bpair_cis = set->n_bpair_cis;
	result->n_bpair_trans = set->n_bpair_trans;
	result->n_bad_iter = loop_diag.n_bad_iter;
	result->n_relax_nonfinite_iter = loop_diag.n_relax_nonfinite_iter;
	result->n_coord_nonfinite = loop_diag.n_coord_nonfinite;
	result->status_ok = loop_diag.n_bad_iter == 0 &&
		loop_diag.n_relax_nonfinite_iter == 0 &&
		loop_diag.n_coord_nonfinite == 0;
	failed |= check_true("matrix result status OK", result->status_ok);
	failed |= check_i32("matrix append summary", append_summary_row(summary_fp, result, write_raw), 0);
	fflush(summary_fp);

	fprintf(stderr,
			"P9016 matrix config %s: final_entropy=%.8g final_pU=%.8g "
			"final_sum_wedge_k=%.8g status=OK\n",
			config->name, result->final_mean_entropy, result->final_mean_pU,
			result->final_sum_wedge_k);

cleanup:
	if (failed)
		fprintf(stderr, "P9016 matrix config %s failed; partial output remains in %s\n",
				config->name, result->output_dir);
	free(haploid);
	free(diploid);
	free(init_diploid);
	free(per_iter);
	hk_blind_bpair_set_destroy(set);
	return failed != 0;
}

int main(void)
{
	struct hk_map *m = 0;
	struct hk_bmap *bmap = 0;
	struct hk_bmap *fine_bmap = 0;
	struct hk_blind_coarse_to_fine_map *coarse_to_fine = 0;
	struct hk_blind_pair *raw = 0;
	struct matrix_result results[sizeof(matrix_configs) / sizeof(matrix_configs[0])];
	char root_dir[512] = {0};
	char summary_path[768];
	FILE *summary_fp = 0;
	int write_raw = 0;
	const char *only_config = 0;
	int bin_size_bp = HK_BLIND_P9016_MATRIX_RESOLUTION;
	int32_t n_raw;
	int32_t i;
	size_t c;
	int n_selected = 0;
	int failed = 0;
	clock_t t0 = clock(), t1;
	double elapsed_sec;

	if (!file_exists(HK_BLIND_P9016_MATRIX_PATH)) {
		fprintf(stderr, "ERROR: %s not found; full P9016 matrix run did not start\n",
				HK_BLIND_P9016_MATRIX_PATH);
		return 1;
	}
	if (!file_exists("./audit_blind_p9016_full_cpu_output.bin")) {
		fprintf(stderr, "ERROR: audit_blind_p9016_full_cpu_output.bin not found; build target dependency first\n");
		return 1;
	}
	write_raw = (getenv("HK_BLIND_WRITE_RAW") != 0 &&
				 strcmp(getenv("HK_BLIND_WRITE_RAW"), "1") == 0);
	only_config = getenv("HK_BLIND_P9016_ONLY_CONFIG");
	bin_size_bp = matrix_bin_size_bp_from_env();
	if (bin_size_bp <= 0)
		return 1;

	hk_verbose = 0;
	fprintf(stderr, "P9016 full CPU matrix: reading %s\n", HK_BLIND_P9016_MATRIX_PATH);
	m = hk_map_read(HK_BLIND_P9016_MATRIX_PATH);
	if (m == 0) {
		fprintf(stderr, "failed to read %s\n", HK_BLIND_P9016_MATRIX_PATH);
		return 1;
	}
	n_raw = m->n_pairs;
	if (n_raw <= 0) {
		fprintf(stderr, "matrix input raw positive: predicate failed\n");
		failed = 1;
		goto cleanup;
	}

	{
		char resolution_label[32];
		fprintf(stderr, "P9016 full CPU matrix: building %s bmap from %d raw pairs\n",
				matrix_resolution_label(bin_size_bp, resolution_label), n_raw);
	}
	if (HK_BLIND_P9016_MATRIX_BASE_K_MODE == HK_BLIND_BASE_K_NEIGHBOR_MEDIAN)
		hk_pair_count_nei(n_raw, m->pairs,
						  HK_BLIND_P9016_MATRIX_BASE_K_NEIGHBOR_RADIUS,
						  HK_BLIND_P9016_MATRIX_BASE_K_NEIGHBOR_RADIUS);
	bmap = hk_bmap_gen(m->d, n_raw, m->pairs, bin_size_bp, 1);
	raw = (struct hk_blind_pair*)calloc((size_t)n_raw, sizeof(*raw));
	if (bmap == 0 || raw == 0) {
		fprintf(stderr, "failed to allocate matrix bmap/raw data\n");
		failed = 1;
		goto cleanup;
	}
	for (i = 0; i < n_raw; ++i)
		hk_blind_pair_from_pair(&raw[i], &m->pairs[i]);
	failed |= check_true("matrix bead count positive", bmap->n_beads > 0);
	if (failed) goto cleanup;
	if (bin_size_bp != HK_BLIND_P9016_MATRIX_RESOLUTION || matrix_configs_require_density_exposure()) {
		fprintf(stderr, "P9016 full CPU matrix: building 1Mb fine bmap for exposure/map diagnostics\n");
		fine_bmap = hk_bmap_gen(m->d, n_raw, m->pairs, HK_BLIND_P9016_MATRIX_RESOLUTION, 1);
		if (fine_bmap == 0 || fine_bmap->n_beads <= 0) {
			fprintf(stderr, "failed to build 1Mb fine bmap for multiresolution map\n");
			failed = 1;
			goto cleanup;
		}
		coarse_to_fine = hk_blind_coarse_to_fine_map_build(bmap, fine_bmap);
		if (coarse_to_fine == 0) {
			fprintf(stderr, "failed to build coarse-to-fine map from %d bp to 1Mb bmap\n", bin_size_bp);
			failed = 1;
			goto cleanup;
		}
	}

	failed |= check_i32("matrix output root", make_output_root(root_dir, sizeof(root_dir)), 0);
	if (failed) goto cleanup;
	{
		char bmap_summary_path[768], fine_bmap_summary_path[768], coarse_to_fine_path[768];
		FILE *bmap_fp;
		path_join(bmap_summary_path, sizeof(bmap_summary_path), root_dir, "bmap_summary.tsv");
		bmap_fp = fopen(bmap_summary_path, "w");
		if (bmap_fp == 0) {
			fprintf(stderr, "failed to open bmap summary %s\n", bmap_summary_path);
			failed = 1;
			goto cleanup;
		}
		failed |= check_i32("matrix write bmap summary",
							hk_blind_write_bmap_summary_tsv(bmap_fp, bmap,
															 coarse_to_fine? coarse_to_fine->parent_child_count : 0), 0);
		if (fclose(bmap_fp) != 0)
			failed = 1;
		if (failed) goto cleanup;
		if (fine_bmap) {
			path_join(fine_bmap_summary_path, sizeof(fine_bmap_summary_path), root_dir, "fine_1mb_bmap_summary.tsv");
			bmap_fp = fopen(fine_bmap_summary_path, "w");
			if (bmap_fp == 0) {
				fprintf(stderr, "failed to open fine bmap summary %s\n", fine_bmap_summary_path);
				failed = 1;
				goto cleanup;
			}
			failed |= check_i32("matrix write fine bmap summary",
								hk_blind_write_bmap_summary_tsv(bmap_fp, fine_bmap, 0), 0);
			if (fclose(bmap_fp) != 0)
				failed = 1;
			if (failed) goto cleanup;
		}
		if (coarse_to_fine) {
			path_join(coarse_to_fine_path, sizeof(coarse_to_fine_path), root_dir, "coarse_to_fine_map.tsv");
			bmap_fp = fopen(coarse_to_fine_path, "w");
			if (bmap_fp == 0) {
				fprintf(stderr, "failed to open coarse-to-fine map %s\n", coarse_to_fine_path);
				failed = 1;
				goto cleanup;
			}
			failed |= check_i32("matrix write coarse-to-fine map",
								hk_blind_write_coarse_to_fine_map_tsv(bmap_fp, bmap, fine_bmap, coarse_to_fine), 0);
			if (fclose(bmap_fp) != 0)
				failed = 1;
			if (failed) goto cleanup;
		}
	}
	if (only_config && only_config[0]) {
		char summary_name[256];
		snprintf(summary_name, sizeof(summary_name), "matrix_summary.%s.tsv", only_config);
		path_join(summary_path, sizeof(summary_path), root_dir, summary_name);
	} else {
		path_join(summary_path, sizeof(summary_path), root_dir, "matrix_summary.tsv");
	}
	summary_fp = fopen(summary_path, "w");
	if (summary_fp == 0) {
		fprintf(stderr, "failed to open matrix summary %s\n", summary_path);
		failed = 1;
		goto cleanup;
	}
	failed |= check_i32("matrix summary header", write_summary_header(summary_fp), 0);
	if (failed) goto cleanup;

	fprintf(stderr, "P9016 full CPU matrix: output root %s write_raw_posterior=%d only_config=%s\n",
			root_dir, write_raw, only_config && only_config[0]? only_config : "all");
	for (c = 0; c < sizeof(matrix_configs) / sizeof(matrix_configs[0]); ++c) {
		if (!matrix_config_is_selected(&matrix_configs[c], only_config))
			continue;
		++n_selected;
		failed |= run_one_config(&matrix_configs[c], bmap, raw, n_raw,
								 root_dir, coarse_to_fine, fine_bmap,
								 bin_size_bp, write_raw, summary_fp, &results[c]);
		if (failed) goto cleanup;
	}
	if (n_selected == 0) {
		fprintf(stderr, "P9016 full CPU matrix: no matrix config matched HK_BLIND_P9016_ONLY_CONFIG=%s\n",
				only_config? only_config : "");
		failed = 1;
		goto cleanup;
	}
	if (fclose(summary_fp) != 0) {
		summary_fp = 0;
		failed = 1;
		goto cleanup;
	}
	summary_fp = 0;
	failed |= validate_summary_file(summary_path, n_selected);
	if (failed) goto cleanup;

	t1 = clock();
	elapsed_sec = (double)(t1 - t0) / (double)CLOCKS_PER_SEC;
	fprintf(stderr, "P9016 full CPU matrix: output_root=%s elapsed_cpu_sec=%.3f status=OK\n",
			root_dir, elapsed_sec);
	for (c = 0; c < sizeof(matrix_configs) / sizeof(matrix_configs[0]); ++c) {
		if (!matrix_config_is_selected(&matrix_configs[c], only_config))
			continue;
		fprintf(stderr,
				"P9016 matrix summary: config=%s final_entropy=%.8g final_pU=%.8g "
				"final_sum_wedge_k=%.8g status=%s\n",
				results[c].config->name, results[c].final_mean_entropy,
				results[c].final_mean_pU, results[c].final_sum_wedge_k,
				results[c].status_ok? "OK" : "WARN");
	}

cleanup:
	if (summary_fp) fclose(summary_fp);
	if (failed)
		fprintf(stderr, "P9016 full CPU matrix failed%s%s\n",
				root_dir[0]? "; partial output remains in " : "",
				root_dir[0]? root_dir : "");
	hk_blind_coarse_to_fine_map_destroy(coarse_to_fine);
	if (fine_bmap) hk_bmap_destroy(fine_bmap);
	free(raw);
	if (bmap) hk_bmap_destroy(bmap);
	if (m) hk_map_destroy(m);
	return failed != 0;
}
