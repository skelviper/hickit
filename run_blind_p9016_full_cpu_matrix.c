static int init_coords_for_config(struct hk_bmap *bmap, const struct matrix_config *config,
								  fvec3_t *haploid, fvec3_t *diploid)
{
	struct hk_fdg_conf scaffold_conf;
	int ret = -1;

	assert(bmap);
	assert(config);
	assert(diploid);
	assert(hk_blind_init_mode_valid(config->init_mode));
	if (config->init_mode == HK_BLIND_INIT_RANDOM_DIPLOID)
		return hk_blind_init_random_diploid_coords(bmap, diploid, config->init_scale, config->init_seed);
	assert(haploid);
	if (config->init_mode == HK_BLIND_INIT_TOY_SPLIT) {
		ret = hk_blind_init_toy_haploid_scaffold(bmap, haploid);
	} else if (config->init_mode == HK_BLIND_INIT_UNPHASED_SCAFFOLD_SPLIT) {
		hk_fdg_conf_init(&scaffold_conf);
		scaffold_conf.backend = HK_FDG_BACKEND_CPU;
		scaffold_conf.n_iter = config->scaffold_fdg_n_iter;
		ret = hk_blind_init_haploid_scaffold_from_bmap_fdg(bmap, &scaffold_conf, haploid,
														   config->init_seed);
	} else if (config->init_mode == HK_BLIND_INIT_RANDOM_HAPLOID_SPLIT) {
		ret = hk_blind_init_random_haploid_scaffold(bmap, haploid, config->init_scale,
													config->init_seed);
	}
	if (ret != 0) return ret;
	return hk_blind_init_diploid_coords_from_haploid(bmap, haploid, bmap->n_beads,
													 diploid, HK_BLIND_P9016_MATRIX_INIT_EPS,
													 HK_BLIND_P9016_MATRIX_INIT_NOISE_SCALE,
													 config->init_seed);
}

