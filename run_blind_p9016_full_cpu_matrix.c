static float mean_adjacent_same_chr_distance(const struct hk_bmap *bmap, const fvec3_t *diploid)
{
	double sum = 0.0;
	int32_t n = 0, bid;
	int copy;

	assert(bmap);
	assert(diploid || bmap->n_beads == 0);
	for (bid = 1; bid < bmap->n_beads; ++bid) {
		if (bmap->beads[bid].chr != bmap->beads[bid - 1].chr)
			continue;
		for (copy = 0; copy < HK_DIPLOID_N_COPY; ++copy) {
			int32_t a = hk_diploid_bid(bid - 1, copy);
			int32_t b = hk_diploid_bid(bid, copy);
			double dx = (double)diploid[b][0] - diploid[a][0];
			double dy = (double)diploid[b][1] - diploid[a][1];
			double dz = (double)diploid[b][2] - diploid[a][2];
			double d = sqrt(dx * dx + dy * dy + dz * dz);
			if (isfinite(d) && d > 0.0) {
				sum += d;
				++n;
			}
		}
	}
	if (n == 0)
		return 0.1f;
	return (float)(sum / (double)n);
}

static int write_lifted_1mb_outputs(const char *out_dir, const struct hk_bmap *coarse_bmap,
									const struct hk_bmap *fine_bmap,
									const struct hk_blind_coarse_to_fine_map *map,
									const fvec3_t *coarse_diploid)
{
	char lifted_path[1024], sanity_path[1024];
	fvec3_t *fine_diploid = 0;
	FILE *fp = 0;
	float mean_adjacent, child_offset_step;
	double max_child_distance = 0.0, sum_child_distance = 0.0;
	int32_t n_mapped = 0, n_nonfinite = 0, fine_bid, copy;
	int ret = -1;

	assert(out_dir);
	assert(coarse_bmap);
	assert(fine_bmap);
	assert(map);
	assert(coarse_diploid);
	assert(map->n_coarse == coarse_bmap->n_beads);
	assert(map->n_fine == fine_bmap->n_beads);

	if (fine_bmap->n_beads > 0)
		fine_diploid = (fvec3_t*)calloc((size_t)fine_bmap->n_beads * HK_DIPLOID_N_COPY,
										sizeof(*fine_diploid));
	if (fine_bmap->n_beads > 0 && fine_diploid == 0)
		goto cleanup;

	mean_adjacent = mean_adjacent_same_chr_distance(coarse_bmap, coarse_diploid);
	child_offset_step = 0.05f * mean_adjacent;
	if (!isfinite(child_offset_step) || child_offset_step <= 0.0f)
		child_offset_step = 0.1f;
	if (hk_blind_lift_from_4mb(coarse_bmap, map, coarse_diploid, fine_diploid,
							   child_offset_step) != 0)
		goto cleanup;

	for (fine_bid = 0; fine_bid < fine_bmap->n_beads; ++fine_bid) {
		int32_t parent = map->fine_to_coarse[fine_bid];
		if (parent < 0 || parent >= coarse_bmap->n_beads)
			goto cleanup;
		++n_mapped;
		for (copy = 0; copy < HK_DIPLOID_N_COPY; ++copy) {
			int32_t src = hk_diploid_bid(parent, copy);
			int32_t dst = hk_diploid_bid(fine_bid, copy);
			double dx = (double)fine_diploid[dst][0] - coarse_diploid[src][0];
			double dy = (double)fine_diploid[dst][1] - coarse_diploid[src][1];
			double dz = (double)fine_diploid[dst][2] - coarse_diploid[src][2];
			double d = sqrt(dx * dx + dy * dy + dz * dz);
			int a;
			if (!isfinite(d)) {
				++n_nonfinite;
			} else {
				sum_child_distance += d;
				if (d > max_child_distance)
					max_child_distance = d;
			}
			for (a = 0; a < 3; ++a)
				if (!isfinite(fine_diploid[dst][a]))
					++n_nonfinite;
		}
	}

	path_join(lifted_path, sizeof(lifted_path), out_dir, "lifted_1mb_init.coords.tsv.gz");
	path_join(sanity_path, sizeof(sanity_path), out_dir, "lift_sanity.tsv");
	if (hk_blind_write_diploid_coords_tsv_gz(lifted_path, fine_bmap, fine_diploid) != 0)
		goto cleanup;
	fp = fopen(sanity_path, "w");
	if (fp == 0)
		goto cleanup;
	if (fprintf(fp,
				"n_fine_beads\tn_mapped\tn_nonfinite\tchild_offset_step\t"
				"mean_coarse_adjacent_distance\tmean_child_distance_to_parent\t"
				"max_child_distance_to_parent\tcopy_labels_are_gauge_only\n"
				"%d\t%d\t%d\t%.9g\t%.9g\t%.9g\t%.9g\t%d\n",
				fine_bmap->n_beads, n_mapped, n_nonfinite, child_offset_step,
				mean_adjacent,
				fine_bmap->n_beads > 0?
					(float)(sum_child_distance / (double)(fine_bmap->n_beads * HK_DIPLOID_N_COPY)) : 0.0f,
				(float)max_child_distance, 1) < 0)
		goto cleanup;
	ret = 0;

cleanup:
	if (fp && fclose(fp) != 0)
		ret = -1;
	free(fine_diploid);
	return ret;
}

static float parent_centroid_rms_distance(const struct hk_blind_coarse_to_fine_map *map,
										  const fvec3_t *fine_diploid,
										  const fvec3_t *coarse_diploid)
{
	double sum2 = 0.0;
	int32_t n = 0;
	int32_t parent, copy;

	assert(map);
	assert(fine_diploid || map->n_fine == 0);
	assert(coarse_diploid || map->n_coarse == 0);
	for (parent = 0; parent < map->n_coarse; ++parent) {
		int32_t n_child = map->parent_child_count[parent];
		if (n_child <= 0) continue;
		for (copy = 0; copy < HK_DIPLOID_N_COPY; ++copy) {
			double centroid[3] = {0.0, 0.0, 0.0};
			double dx, dy, dz;
			int32_t fine_bid;
			int a;
			for (fine_bid = 0; fine_bid < map->n_fine; ++fine_bid) {
				if (map->fine_to_coarse[fine_bid] != parent)
					continue;
				for (a = 0; a < 3; ++a)
					centroid[a] += fine_diploid[hk_diploid_bid(fine_bid, copy)][a];
			}
			for (a = 0; a < 3; ++a)
				centroid[a] /= (double)n_child;
			dx = centroid[0] - (double)coarse_diploid[hk_diploid_bid(parent, copy)][0];
			dy = centroid[1] - (double)coarse_diploid[hk_diploid_bid(parent, copy)][1];
			dz = centroid[2] - (double)coarse_diploid[hk_diploid_bid(parent, copy)][2];
			if (isfinite(dx) && isfinite(dy) && isfinite(dz)) {
				sum2 += dx * dx + dy * dy + dz * dz;
				++n;
			}
		}
	}
	return n > 0? (float)sqrt(sum2 / (double)n) : 0.0f;
}

static int run_lifted_1mb_refinement(const char *out_dir,
									 const struct matrix_config *parent_config,
									 const struct hk_bmap *coarse_bmap,
									 const struct hk_bmap *fine_bmap,
									 const struct hk_blind_coarse_to_fine_map *map,
									 const fvec3_t *coarse_diploid,
									 const struct hk_blind_pair *raw,
									 int32_t n_raw)
{
	struct matrix_config refine_config;
	struct hk_blind_bpair_set *fine_set = 0;
	struct hk_fdg_conf fdg_conf;
	struct hk_blind_iter_schedule_conf schedule_conf;
	struct hk_blind_iter_loop_diag loop_diag;
	struct hk_blind_prior_diag prior_diag;
	struct hk_blind_single_iter_diag *per_iter = 0;
	fvec3_t *fine_diploid = 0;
	char lifted_path[1024], coords_gz_path[1024], loop_path[1024], force_path[1024];
	char posterior_path[1024], anchor_path[1024], manifest_path[1024];
	FILE *fp = 0;
	float child_offset_step, initial_anchor_rms, final_anchor_rms, anchor_k;
	int32_t n_diploid, n_iter, relax_steps;
	int write_posterior;
	int ret = -1;

	assert(out_dir);
	assert(parent_config);
	assert(coarse_bmap);
	assert(fine_bmap);
	assert(map);
	assert(coarse_diploid);
	assert(raw || n_raw == 0);
	assert(map->n_coarse == coarse_bmap->n_beads);
	assert(map->n_fine == fine_bmap->n_beads);

	n_iter = matrix_env_i32("HK_BLIND_P9016_MR_REFINE_N_ITER", 2);
	relax_steps = matrix_env_i32("HK_BLIND_P9016_MR_REFINE_RELAX_STEPS", 5);
	anchor_k = matrix_env_float("HK_BLIND_P9016_MR_REFINE_ANCHOR_K", 0.05f);
	write_posterior = !matrix_env_flag_enabled("HK_BLIND_P9016_MR_REFINE_SKIP_POSTERIOR");

	refine_config = *parent_config;
	refine_config.name = "lifted_1mb_parent_anchor_refine";
	refine_config.init_mode = HK_BLIND_INIT_UNPHASED_SCAFFOLD_SPLIT;
	refine_config.prior_mode = HK_BLIND_PRIOR_CIS_INTER_RATIO;
	refine_config.rho_train_mode = HK_BLIND_RHO_TRAIN_ENTROPY;
	refine_config.d_scale_mode = HK_BLIND_D_SCALE_RAW_COUNT;
	refine_config.n_iter = n_iter;
	refine_config.relax_steps = relax_steps;
	refine_config.relax_step = HK_BLIND_P9016_MATRIX_REFERENCE_RELAX_STEP;
	refine_config.repulsion_multiplier = parent_config->repulsion_multiplier;
	refine_config.temperature_start = 2.0f;
	refine_config.temperature_end = 1.0f;
	refine_config.rho_train_start = 1.0f;
	refine_config.rho_train_end = 1.0f;
	refine_config.rho_train_floor = HK_BLIND_RHO_TRAIN_DEFAULT_FLOOR;
	refine_config.contact_k_multiplier_cis = 1.0f;
	refine_config.contact_k_multiplier_trans = 1.0f;

	n_diploid = fine_bmap->n_beads * HK_DIPLOID_N_COPY;
	fine_diploid = n_diploid > 0? (fvec3_t*)calloc((size_t)n_diploid, sizeof(*fine_diploid)) : 0;
	per_iter = n_iter > 0? (struct hk_blind_single_iter_diag*)calloc((size_t)n_iter, sizeof(*per_iter)) : 0;
	if ((n_diploid > 0 && fine_diploid == 0) || (n_iter > 0 && per_iter == 0))
		goto cleanup;

	child_offset_step = 0.05f * mean_adjacent_same_chr_distance(coarse_bmap, coarse_diploid);
	if (!isfinite(child_offset_step) || child_offset_step <= 0.0f)
		child_offset_step = 0.1f;
	if (hk_blind_lift_from_4mb(coarse_bmap, map, coarse_diploid, fine_diploid,
							   child_offset_step) != 0)
		goto cleanup;
	initial_anchor_rms = parent_centroid_rms_distance(map, fine_diploid, coarse_diploid);

	fine_set = hk_blind_bpair_set_build(fine_bmap, n_raw, raw);
	if (fine_set == 0)
		goto cleanup;
	if (init_prior_for_config(fine_bmap, fine_set, &refine_config, &prior_diag) != 0)
		goto cleanup;
	hk_fdg_conf_init(&fdg_conf);
	fdg_conf.backend = HK_FDG_BACKEND_CPU;
	fdg_conf.k_rel_rep *= refine_config.repulsion_multiplier;
	set_schedule_conf(&schedule_conf, &refine_config);

	path_join(lifted_path, sizeof(lifted_path), out_dir, "refine_1mb_lifted_init.coords.tsv.gz");
	path_join(coords_gz_path, sizeof(coords_gz_path), out_dir, "refine_1mb.coords.tsv.gz");
	path_join(loop_path, sizeof(loop_path), out_dir, "refine_1mb.loop_diag.tsv");
	path_join(force_path, sizeof(force_path), out_dir, "refine_1mb.force_class_diag.tsv");
	path_join(posterior_path, sizeof(posterior_path), out_dir, "refine_1mb.bpair_posterior.tsv");
	path_join(anchor_path, sizeof(anchor_path), out_dir, "refine_1mb.anchor_diag.tsv");
	path_join(manifest_path, sizeof(manifest_path), out_dir, "refine_1mb.manifest.tsv");

	if (hk_blind_write_diploid_coords_tsv_gz(lifted_path, fine_bmap, fine_diploid) != 0)
		goto cleanup;
	fprintf(stderr, "P9016 matrix config %s: running lifted 1Mb anchored refinement n_iter=%d relax_steps=%d anchor_k=%.9g\n",
			parent_config->name, n_iter, relax_steps, anchor_k);
	if (hk_blind_run_iter_loop_scheduled_parent_anchor_cpu(fine_bmap, fine_set, &fdg_conf, fine_diploid,
														   0, &schedule_conf, map, coarse_diploid,
														   anchor_k, per_iter, &loop_diag) != 0)
		goto cleanup;
	if (loop_diag.n_bad_iter != 0 || loop_diag.n_relax_nonfinite_iter != 0 || loop_diag.n_coord_nonfinite != 0)
		goto cleanup;
	final_anchor_rms = parent_centroid_rms_distance(map, fine_diploid, coarse_diploid);
	if (hk_blind_write_diploid_coords_tsv_gz(coords_gz_path, fine_bmap, fine_diploid) != 0)
		goto cleanup;
	fp = fopen(loop_path, "w");
	if (fp == 0) goto cleanup;
	if (hk_blind_write_iter_loop_diag_tsv(fp, &loop_diag) != 0) goto cleanup;
	if (fclose(fp) != 0) { fp = 0; goto cleanup; }
	fp = 0;
	if (write_force_class_diag(force_path, &fdg_conf, &refine_config, fine_bmap, fine_set, fine_diploid,
							   n_iter > 0? &per_iter[n_iter - 1].relax_diag : 0) != 0)
		goto cleanup;
	if (write_posterior) {
		fp = fopen(posterior_path, "w");
		if (fp == 0) goto cleanup;
		if (hk_blind_write_bpair_posterior_tsv(fp, fine_bmap, fine_set) != 0) goto cleanup;
		if (fclose(fp) != 0) { fp = 0; goto cleanup; }
		fp = 0;
	}
	fp = fopen(anchor_path, "w");
	if (fp == 0) goto cleanup;
	if (fprintf(fp,
				"parent_config\tn_iter\trelax_steps\tanchor_k\tchild_offset_step\t"
				"initial_parent_centroid_rms\tfinal_parent_centroid_rms\t"
				"final_anchor_energy\tfinal_anchor_force_l1\tn_anchor_nonfinite_step\t"
				"copy_labels_are_gauge_only\n"
				"%s\t%d\t%d\t%.9g\t%.9g\t%.9g\t%.9g\t%.9g\t%.9g\t%d\t%d\n",
				parent_config->name, n_iter, relax_steps, anchor_k, child_offset_step,
				initial_anchor_rms, final_anchor_rms,
				loop_diag.final_anchor_energy, loop_diag.final_anchor_force_l1,
				loop_diag.n_anchor_nonfinite_step, 1) < 0)
		goto cleanup;
	if (fclose(fp) != 0) { fp = 0; goto cleanup; }
	fp = 0;
	fp = fopen(manifest_path, "w");
	if (fp == 0) goto cleanup;
	if (fprintf(fp,
				"key\tvalue\n"
				"sample\tP9016\n"
				"mode\t4mb_to_1mb_lifted_parent_anchor_refine\n"
				"parent_config\t%s\n"
				"init_mode\tlift_from_4mb\n"
				"prior_mode\t%s\n"
				"rho_train_mode\t%s\n"
				"d_scale_mode\t%s\n"
				"n_iter\t%d\n"
				"relax_steps\t%d\n"
				"anchor_mode\tparent_centroid_anchor\n"
				"anchor_k\t%.9g\n"
				"child_offset_step\t%.9g\n"
				"copy_labels_are_gauge_only\t1\n"
				"uses_phase_labels\t0\n"
				"uses_charm_or_reference\t0\n"
				"output_lifted_init\t%s\n"
				"output_coords_gz\t%s\n"
				"output_loop_diag\t%s\n"
				"output_force_class_diag\t%s\n"
				"output_bpair_posterior\t%s\n"
				"output_anchor_diag\t%s\n"
				"final_mean_entropy\t%.9g\n"
				"final_mean_pU\t%.9g\n"
				"final_parent_centroid_rms\t%.9g\n"
				"final_anchor_energy\t%.9g\n"
				"final_anchor_force_l1\t%.9g\n"
				"status\tOK\n",
				parent_config->name,
				hk_blind_prior_mode_name(refine_config.prior_mode),
				hk_blind_rho_train_mode_name(refine_config.rho_train_mode),
				hk_blind_d_scale_mode_name(refine_config.d_scale_mode),
				n_iter, relax_steps, anchor_k, child_offset_step,
				lifted_path, coords_gz_path, loop_path, force_path,
				write_posterior? posterior_path : "disabled_by_HK_BLIND_P9016_MR_REFINE_SKIP_POSTERIOR",
				anchor_path,
				loop_diag.final_mean_entropy, loop_diag.final_mean_pU,
				final_anchor_rms, loop_diag.final_anchor_energy,
				loop_diag.final_anchor_force_l1) < 0)
		goto cleanup;
	ret = 0;

cleanup:
	if (fp && fclose(fp) != 0)
		ret = -1;
	if (ret != 0)
		fprintf(stderr, "P9016 matrix config %s: lifted 1Mb anchored refinement failed\n",
				parent_config->name);
	free(fine_diploid);
	free(per_iter);
	hk_blind_bpair_set_destroy(fine_set);
	return ret;
}

