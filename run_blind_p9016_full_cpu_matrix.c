static int check_binned_set(const struct hk_bmap *bmap, const struct hk_blind_bpair_set *set,
							int32_t n_raw)
{
	int failed = 0;
	int32_t i;

	failed |= check_true("matrix set exists", set != 0);
	if (set == 0) return 1;
	failed |= check_i32("matrix raw count", set->n_raw, n_raw);
	failed |= check_true("matrix bpair positive", set->n_bpairs > 0);
	failed |= check_i32("matrix raw class count", (int32_t)(set->n_raw_cis + set->n_raw_trans), set->n_raw);
	failed |= check_i32("matrix bpair class count", set->n_bpair_cis + set->n_bpair_trans, set->n_bpairs);
	for (i = 0; i < set->n_raw; ++i) {
		failed |= check_true("matrix raw2binned id lower", set->raw2binned[i].bpair_id >= 0);
		failed |= check_true("matrix raw2binned id upper", set->raw2binned[i].bpair_id < set->n_bpairs);
		failed |= check_true("matrix raw2binned swapped",
							 set->raw2binned[i].swapped == 0 || set->raw2binned[i].swapped == 1);
	}
	for (i = 0; i < set->n_bpairs; ++i) {
		const struct hk_blind_bpair *bp = &set->bpairs[i];
		failed |= check_true("matrix key sorted", bp->key.bid[0] <= bp->key.bid[1]);
		failed |= check_true("matrix key bid0 valid", bp->key.bid[0] >= 0 && bp->key.bid[0] < bmap->n_beads);
		failed |= check_true("matrix key bid1 valid", bp->key.bid[1] >= 0 && bp->key.bid[1] < bmap->n_beads);
		failed |= check_true("matrix contact class valid",
							 bp->contact_class == HK_BLIND_CONTACT_CIS ||
							 bp->contact_class == HK_BLIND_CONTACT_TRANS);
		failed |= check_i32("matrix contact class matches chromosome",
							bp->contact_class,
							bmap->beads[bp->key.bid[0]].chr == bmap->beads[bp->key.bid[1]].chr?
							HK_BLIND_CONTACT_CIS : HK_BLIND_CONTACT_TRANS);
	}
	return failed;
}

static int check_loop_health(const struct matrix_config *config,
							 const struct hk_blind_iter_loop_diag *diag,
							 const struct hk_blind_single_iter_diag *per_iter)
{
	int failed = 0;
	int32_t i;
	double expected_final_temperature = config->n_iter <= 1?
		config->temperature_start : config->temperature_end;
	double expected_final_rho = config->n_iter <= 1?
		config->rho_train_start : config->rho_train_end;

	failed |= check_i32("matrix loop n_iter", diag->n_iter, config->n_iter);
	failed |= check_i32("matrix loop completed", diag->n_completed, config->n_iter);
	failed |= check_i32("matrix loop bad iter", diag->n_bad_iter, 0);
	failed |= check_i32("matrix loop relax bad", diag->n_relax_nonfinite_iter, 0);
	failed |= check_i32("matrix loop coord bad", diag->n_coord_nonfinite, 0);
	failed |= check_close("matrix initial temperature", diag->initial_temperature, config->temperature_start);
	failed |= check_close("matrix final temperature", diag->final_temperature, expected_final_temperature);
	failed |= check_close("matrix initial rho", diag->initial_rho_train, config->rho_train_start);
	failed |= check_close("matrix final rho", diag->final_rho_train, expected_final_rho);
	failed |= check_true("matrix final entropy finite", isfinite(diag->final_mean_entropy));
	failed |= check_true("matrix final entropy range", diag->final_mean_entropy >= -1e-6f &&
						 diag->final_mean_entropy <= logf((float)HK_BLIND_N_STATE) + 1e-6f);
	failed |= check_true("matrix final pU finite", isfinite(diag->final_mean_pU));
	failed |= check_true("matrix final pU range",
						 diag->final_mean_pU >= -1e-6f && diag->final_mean_pU <= 1.0f + 1e-6f);
	failed |= check_true("matrix final sep finite", isfinite(diag->final_mean_sep));
	failed |= check_true("matrix final sum k finite", isfinite(diag->final_sum_wedge_k));
	failed |= check_true("matrix final sum k nonnegative", diag->final_sum_wedge_k >= 0.0);
	for (i = 0; i < config->n_iter; ++i) {
		const struct hk_blind_iter_diag *pre = &per_iter[i].pre_relax_diag;
		failed |= check_i32("matrix posterior nonfinite", pre->n_posterior_nonfinite, 0);
		failed |= check_i32("matrix posterior bad sum", pre->n_posterior_bad_sum, 0);
		failed |= check_i32("matrix posterior out of range", pre->n_posterior_out_of_range, 0);
		failed |= check_i32("matrix uncertainty nonfinite", pre->n_uncertainty_nonfinite, 0);
		failed |= check_i32("matrix uncertainty out of range", pre->n_uncertainty_out_of_range, 0);
		failed |= check_i32("matrix five-state bad sum", pre->n_five_state_bad_sum, 0);
		failed |= check_i32("matrix wedge nonfinite", pre->n_wedge_nonfinite, 0);
		failed |= check_i32("matrix wedge bad k", pre->n_wedge_bad_k, 0);
		failed |= check_i32("matrix wedge bad d_scale", pre->n_wedge_bad_d_scale, 0);
		failed |= check_i32("matrix sep force nonfinite", pre->sep_force_nonfinite, 0);
		failed |= check_i32("matrix relax completed", per_iter[i].relax_diag.n_completed, config->relax_steps);
		failed |= check_i32("matrix relax nonfinite step", per_iter[i].relax_diag.n_nonfinite_step, 0);
		failed |= check_i32("matrix relax coord bad", per_iter[i].relax_diag.n_coord_nonfinite, 0);
		failed |= check_i32("matrix backbone bad", per_iter[i].relax_diag.n_backbone_nonfinite_step, 0);
		failed |= check_i32("matrix repulsion bad", per_iter[i].relax_diag.n_repulsion_nonfinite_step, 0);
		failed |= check_true("matrix relax total finite", isfinite(per_iter[i].relax_diag.final_total_energy));
		failed |= check_true("matrix repulsion finite", isfinite(per_iter[i].relax_diag.final_repulsion_energy));
	}
	return failed;
}

